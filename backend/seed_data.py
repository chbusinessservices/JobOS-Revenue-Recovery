def _seed_audit(opportunities):
    events = []
    for opp in opportunities:
        events.append({
            "id": f"audit-{opp['id']}-detected",
            "opportunity_id": opp["id"],
            "customer_id": opp["customer_id"],
            "event": "Opportunity Detected",
            "actor": "System",
            "detail": f"{opp['type']} classified as {opp['service_need']}.",
            "timestamp": opp["detected_at"],
        })
        events.append({
            "id": f"audit-{opp['id']}-draft",
            "opportunity_id": opp["id"],
            "customer_id": opp["customer_id"],
            "event": "Draft Generated",
            "actor": "AI Agent",
            "detail": "Approved seeded draft prepared from customer context.",
            "timestamp": opp["detected_at"],
        })
    return sorted(events, key=lambda x: x["timestamp"], reverse=True)


